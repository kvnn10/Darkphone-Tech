-- Darkphone Tech initial schema
create extension if not exists pgcrypto;

create type public.app_role as enum ('owner','admin','sales','technician','cashier');
create type public.sale_status as enum ('completed','voided','pending');
create type public.payment_method as enum ('cash','debit_card','credit_card','bank_transfer','nequi','daviplata','other');
create type public.service_status as enum ('received','diagnosing','awaiting_approval','awaiting_parts','in_repair','ready','delivered','cancelled');

create table public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text not null default '',
 role public.app_role not null default 'sales',
 active boolean not null default true,
 created_at timestamptz not null default now()
);

create or replace function public.is_active_user()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles p where p.id=auth.uid() and p.active=true); $$;

create or replace function public.has_role(allowed public.app_role[])
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles p where p.id=auth.uid() and p.active=true and p.role=any(allowed)); $$;

create table public.customers (
 id uuid primary key default gen_random_uuid(),
 full_name text not null,
 phone text,
 email text,
 document_number text,
 notes text,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);

create table public.products (
 id uuid primary key default gen_random_uuid(),
 name text not null,
 brand text,
 model text,
 sku text unique,
 category text not null default 'Otros',
 cost_price numeric(14,2) not null default 0 check(cost_price>=0),
 selling_price numeric(14,2) not null default 0 check(selling_price>=0),
 stock_quantity integer not null default 0 check(stock_quantity>=0),
 min_stock integer not null default 0 check(min_stock>=0),
 has_imei boolean not null default false,
 active boolean not null default true,
 notes text,
 created_by uuid references public.profiles(id),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);

create table public.product_serials (
 id uuid primary key default gen_random_uuid(),
 product_id uuid not null references public.products(id),
 serial_number text not null unique,
 status text not null default 'available' check(status in ('available','sold','in_service','returned','warranty')),
 purchase_cost numeric(14,2) not null default 0 check(purchase_cost>=0),
 created_at timestamptz not null default now()
);

create table public.cash_sessions (
 id uuid primary key default gen_random_uuid(),
 opened_by uuid not null references public.profiles(id),
 opened_at timestamptz not null default now(),
 opening_amount numeric(14,2) not null default 0 check(opening_amount>=0),
 closed_by uuid references public.profiles(id),
 closed_at timestamptz,
 expected_amount numeric(14,2),
 counted_amount numeric(14,2),
 notes text,
 check((closed_at is null) or (counted_amount is not null))
);
create unique index one_open_cash_session_per_store on public.cash_sessions ((true)) where closed_at is null;

create table public.sales (
 id uuid primary key default gen_random_uuid(),
 sale_number bigint generated by default as identity unique,
 customer_id uuid references public.customers(id),
 cash_session_id uuid references public.cash_sessions(id),
 status public.sale_status not null default 'completed',
 subtotal numeric(14,2) not null default 0 check(subtotal>=0),
 discount numeric(14,2) not null default 0 check(discount>=0),
 total numeric(14,2) not null default 0 check(total>=0),
 notes text,
 created_by uuid references public.profiles(id),
 created_at timestamptz not null default now()
);
create table public.sale_items (
 id uuid primary key default gen_random_uuid(),
 sale_id uuid not null references public.sales(id),
 product_id uuid not null references public.products(id),
 serial_id uuid references public.product_serials(id),
 quantity integer not null check(quantity>0),
 unit_price numeric(14,2) not null check(unit_price>=0),
 unit_cost numeric(14,2) not null default 0 check(unit_cost>=0),
 line_total numeric(14,2) not null check(line_total>=0),
 created_at timestamptz not null default now()
);
create table public.sale_payments (
 id uuid primary key default gen_random_uuid(),
 sale_id uuid not null references public.sales(id),
 method public.payment_method not null,
 amount numeric(14,2) not null check(amount>0),
 reference text,
 paid_at timestamptz not null default now(),
 received_by uuid references public.profiles(id)
);

create table public.cash_movements (
 id uuid primary key default gen_random_uuid(),
 cash_session_id uuid not null references public.cash_sessions(id),
 kind text not null check(kind in ('income','expense','withdrawal','adjustment')),
 amount numeric(14,2) not null check(amount>0),
 category text not null,
 description text,
 reference text,
 created_by uuid references public.profiles(id),
 created_at timestamptz not null default now()
);
create table public.expenses (
 id uuid primary key default gen_random_uuid(),
 cash_session_id uuid references public.cash_sessions(id),
 category text not null,
 concept text not null,
 amount numeric(14,2) not null check(amount>0),
 payment_method public.payment_method not null default 'cash',
 receipt_number text,
 notes text,
 created_by uuid references public.profiles(id),
 created_at timestamptz not null default now()
);

create table public.service_orders (
 id uuid primary key default gen_random_uuid(),
 order_number bigint generated by default as identity unique,
 customer_id uuid references public.customers(id),
 product_id uuid references public.products(id),
 serial_number text,
 device_name text not null,
 reported_fault text not null,
 diagnosis text,
 work_notes text,
 status public.service_status not null default 'received',
 estimated_cost numeric(14,2) not null default 0 check(estimated_cost>=0),
 final_cost numeric(14,2) check(final_cost is null or final_cost>=0),
 parts_cost numeric(14,2) not null default 0 check(parts_cost>=0),
 received_at timestamptz not null default now(),
 promised_at timestamptz,
 delivered_at timestamptz,
 created_by uuid references public.profiles(id),
 updated_at timestamptz not null default now()
);
create table public.service_payments (
 id uuid primary key default gen_random_uuid(),
 service_order_id uuid not null references public.service_orders(id),
 amount numeric(14,2) not null check(amount>0),
 method public.payment_method not null,
 reference text,
 created_by uuid references public.profiles(id),
 created_at timestamptz not null default now()
);

create table public.warranties (
 id uuid primary key default gen_random_uuid(),
 sale_item_id uuid references public.sale_items(id),
 product_serial_id uuid references public.product_serials(id),
 customer_id uuid references public.customers(id),
 starts_at date not null default current_date,
 ends_at date not null,
 terms text,
 status text not null default 'active' check(status in ('active','expired','claimed','voided')),
 claim_notes text,
 resolution text,
 created_at timestamptz not null default now(),
 check(ends_at>=starts_at)
);

create table public.inventory_movements (
 id uuid primary key default gen_random_uuid(),
 product_id uuid not null references public.products(id),
 serial_id uuid references public.product_serials(id),
 movement_type text not null check(movement_type in ('opening','purchase','sale','sale_void','service_use','return','adjustment')),
 quantity_delta integer not null check(quantity_delta<>0),
 unit_cost numeric(14,2) not null default 0,
 reference_type text,
 reference_id uuid,
 notes text,
 created_by uuid references public.profiles(id),
 created_at timestamptz not null default now()
);
create table public.audit_log (
 id bigint generated always as identity primary key,
 actor_id uuid references public.profiles(id),
 action text not null,
 entity text not null,
 entity_id text,
 details jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);

