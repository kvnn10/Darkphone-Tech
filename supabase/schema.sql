create policy "Profiles read own or admin" on public.profiles for select to authenticated using(id=auth.uid() or public.has_role(array['owner','admin']::public.app_role[]));
create policy "Admins manage profiles" on public.profiles for all to authenticated using(public.has_role(array['owner','admin']::public.app_role[])) with check(public.has_role(array['owner','admin']::public.app_role[]));

create policy "Active users read customers" on public.customers for select to authenticated using(public.is_active_user());
create policy "Sales staff manage customers" on public.customers for all to authenticated using(public.has_role(array['owner','admin','sales','cashier','technician']::public.app_role[])) with check(public.has_role(array['owner','admin','sales','cashier','technician']::public.app_role[]));

create policy "Active users read products" on public.products for select to authenticated using(public.is_active_user());
create policy "Admins sales manage products" on public.products for all to authenticated using(public.has_role(array['owner','admin','sales']::public.app_role[])) with check(public.has_role(array['owner','admin','sales']::public.app_role[]));
create policy "Active users read serials" on public.product_serials for select to authenticated using(public.is_active_user());
create policy "Admins manage serials" on public.product_serials for all to authenticated using(public.has_role(array['owner','admin']::public.app_role[])) with check(public.has_role(array['owner','admin']::public.app_role[]));

create policy "Active users read cash sessions" on public.cash_sessions for select to authenticated using(public.is_active_user());
create policy "Cashiers manage own cash session" on public.cash_sessions for all to authenticated using(public.is_active_user() and (opened_by=auth.uid() or public.has_role(array['owner','admin']::public.app_role[]))) with check(public.is_active_user() and public.has_role(array['owner','admin','cashier']::public.app_role[]));
